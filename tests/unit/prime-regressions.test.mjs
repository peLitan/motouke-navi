// F77c: F77a の後に見つかった、前の版より悪くなった2つの文。文はすべて架空
import test from 'node:test';
import assert from 'node:assert/strict';
import { findPrimeExperience } from '../../src/prime-experience.mjs';

const hit = (s) => assert.equal(findPrimeExperience(s), s, s);
const miss = (s) => assert.equal(findPrimeExperience(s), null, s);
const WORK = '元請として同種工事の施工実績を有すること。';
const LIST_WORDS = ['及び', 'および', '並びに', 'ならびに', '又は', 'または', '若しくは', 'もしくは'];

test('(1) 会社の語が技術者を修飾するだけの文は、技術者の文として出さない', () => {
  miss('共同企業体の配置予定技術者は、' + WORK);
  miss('入札参加者の配置する技術者は、' + WORK);
  miss('申請者の配置予定技術者の要件：元請として同種工事を施工した経験を有すること。');
});

test('(1) 「と」: 雇用の関係を書いた文は並べる語ではない', () => {
  miss('入札参加者と直接的かつ恒常的な雇用関係にある技術者は、' + WORK);
  miss('入札参加者と雇用関係にある配置予定技術者は、' + WORK);
  miss('入札参加者と直接雇用する配置予定技術者は、' + WORK);
  miss('入札参加者と資本の関係がある会社の技術者は、' + WORK);
});

test('(1) 会社の語の直後に並べる語が続く文は、会社への条件のまま', () => {
  for (const head of [
    '入札参加者及び配置予定技術者は、',
    '入札参加者並びに配置予定技術者は、',
    '入札参加者と配置予定技術者は、',
    '入札参加者等及び配置予定技術者は、',
    '企業又は配置予定技術者が、',
    '企業・配置予定技術者は、',
    '共同企業体及び配置予定技術者は、',
    '会社など及び配置予定技術者は、',
    '法人 及び 配置予定技術者は、',
    '申請者及び配置予定技術者は、',
  ]) hit(head + WORK);
  for (const word of LIST_WORDS) hit('企業' + word + '配置予定技術者は、' + WORK);
});

test('(1) 技術者より後の会社の語は見ない', () => {
  miss('配置予定技術者は入札参加者と元請として同種工事の施工実績を有すること。');
});

test('(2) 読点の無い文で実績の条件が先に来て閉じていれば、技術者の文としない', () => {
  for (const s of [
    '元請として同種工事の施工実績を有すること及び配置予定技術者の資格を有すること。',
    '元請としての施工実績及び配置予定技術者の資格を有すること。',
    '元請として同種工事の施工実績を有しかつ配置予定技術者の資格を有すること。',
    '元請として同種工事の施工実績を有し配置予定技術者は専任であること。',
    '元請として同種工事の施工実績があり配置予定技術者は専任であること。',
    '元請として同種工事の施工実績を有することかつ配置予定技術者の資格を有すること。',
    '元請として同種工事の施工実績を有するもの及び配置予定技術者の資格を有すること。',
    '元請として同種工事の施工実績を有する者及び配置予定技術者の資格を有する者であること。',
    '元請として同種工事の施工実績を有すること及び同種工事の経験を有する監理技術者を配置すること。',
  ]) hit(s);
  for (const word of LIST_WORDS) hit('元請としての施工実績' + word + '配置予定技術者の資格を有すること。');
});

test('(2) 実績が会社を修飾する文は、会社への条件のまま', () => {
  hit('元請として同種工事の施工実績を有する企業の配置予定技術者は、専任であること。');
  hit('元請として同種工事の施工実績を有する入札参加者の配置する技術者は、専任であること。');
});

test('(2) 実績が技術者を修飾する文は、技術者の文のまま', () => {
  for (const s of [
    '元請として同種工事の施工実績を有する配置予定技術者は、専任であること。',
    '元請として同種工事の施工実績がある配置予定技術者は、専任であること。',
    '元請として同種工事の施工実績を有した配置予定技術者は、専任であること。',
    '同種工事の施工実績を元請として有している監理技術者は、専任であること。',
    '元請として同種工事の施工実績を有する監理技術者又は主任技術者は、専任であること。',
    '元請として同種工事の施工実績を有する主任技術者及び監理技術者を配置すること。',
    '配置予定技術者は同種工事の施工実績及び元請としての経験を有すること。',
  ]) miss(s);
});

test('残る限界(評価.md に書いた)', () => {
  miss('共同企業体の構成員及び配置予定技術者は、' + WORK);
  miss('配置予定技術者の資格を有すること及び' + WORK);
  miss('元請として同種工事の施工実績を有し、かつ、同種工事の経験を有する監理技術者を配置すること。');
  hit('入札参加者又は構成員の配置予定技術者は、' + WORK);
});
